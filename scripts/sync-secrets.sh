#!/bin/sh
# Derive Config/Secrets.xcconfig from .env.
#
# .env is the human-facing source of truth (gitignored). An iOS target cannot read
# it at runtime, so this copies ONLY UNSPLASH_ACCESS_KEY into the gitignored
# xcconfig that the build turns into an Info.plist value.
# UNSPLASH_SECRET_KEY is deliberately never copied: search is a public action and
# the secret key must not ship in the app.
#
# Re-run after editing .env:  scripts/sync-secrets.sh

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"
OUT="$ROOT/Config/Secrets.xcconfig"

if [ ! -f "$ENV_FILE" ]; then
  echo "sync-secrets: $ENV_FILE not found; writing an empty key (app will use fallback visuals)." >&2
  KEY=""
else
  KEY="$(grep -E '^[[:space:]]*UNSPLASH_ACCESS_KEY[[:space:]]*=' "$ENV_FILE" | head -n 1 | cut -d= -f2- | tr -d "\"'[:space:]" || true)"
fi

if [ -z "$KEY" ]; then
  echo "sync-secrets: UNSPLASH_ACCESS_KEY is missing or empty in .env; app will use fallback visuals." >&2
fi

mkdir -p "$ROOT/Config"
{
  echo "// GENERATED by scripts/sync-secrets.sh from .env. Gitignored. Do not edit or commit."
  echo "UNSPLASH_ACCESS_KEY = $KEY"
} > "$OUT"

echo "sync-secrets: wrote $OUT (access key only; secret key not copied)."
